import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';
import ts from 'typescript';
import vm from 'node:vm';
const load = (file, dependencies = {}) => { const code = ts.transpileModule(readFileSync(new URL(file, import.meta.url), 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText; const exports = {}; new Function('require', 'exports', code)(name => dependencies[name], exports); return exports; };
const data = load('./utility-preview-data.ts', { './history': load('./history.ts') });
test('basic items are independent versioned records', () => {
  const rows = data.initialBasicItems();
  const next = data.saveBasicItem(rows, { name: '标识卡', category: '办公用品', unit: '张', note: '', active: true, reason: '新增' });
  assert.equal(next.length, 3); assert.equal(next[0].version, 1);
  assert.throws(() => data.saveBasicItem(next, { name: '文件夹', category: '办公用品', unit: '个', note: '', active: true, reason: '重复' }), /已存在/);
  assert.throws(() => data.saveBasicItem(next, { name: '改名', category: '耗材', unit: '个', note: '', active: true, reason: '旧版本' }, next[0].id, 0), /版本/);
});
test('local interface preferences normalize storage values', () => {
  let contents = '';
  let mode = '';
  const media = { matches: false, addEventListener: (_event, callback) => { media.change = callback; } };
  globalThis.localStorage = { getItem: () => contents, setItem: (_key, value) => { contents = value; } };
  globalThis.window = { matchMedia: query => query.includes('reduced-motion') ? { matches: false } : media };
  globalThis.document = { documentElement: { getAttribute: () => mode, setAttribute: (_name, value) => { mode = value; }, style: {} } };
  vm.runInThisContext(readFileSync(new URL('../../../public/theme-init.js', import.meta.url), 'utf8'));
  assert.deepEqual(data.readPreferences(), data.defaultPreferences);
  assert.equal(mode, 'light');
  media.matches = true; media.change(); assert.equal(mode, 'dark');
  globalThis.previewTheme.apply('light'); assert.equal(mode, 'light');
  data.savePreferences({ density: 'compact', defaultPage: 'workbenchHome', theme: 'dark' });
  assert.deepEqual(data.readPreferences(), { density: 'compact', defaultPage: 'workbenchHome', theme: 'dark' });
  media.matches = false; media.change(); assert.equal(mode, 'dark');
  data.savePreferences({ density: 'compact', defaultPage: 'workbenchHome', theme: 'system' });
  media.change(); assert.equal(mode, 'light');
  contents = '{"density":"compact","defaultPage":"workbenchHome"}';
  assert.deepEqual(data.readPreferences(), { density: 'compact', defaultPage: 'workbenchHome', theme: 'system' });
  contents = '{"theme":"invalid"}'; assert.deepEqual(data.readPreferences(), data.defaultPreferences);
  contents = '{bad'; assert.deepEqual(data.readPreferences(), data.defaultPreferences);
  globalThis.localStorage = { getItem: () => { throw new Error('blocked'); }, setItem: () => { throw new Error('blocked'); } };
  assert.deepEqual(data.readPreferences(), data.defaultPreferences);
  assert.throws(() => data.savePreferences(data.defaultPreferences), /无法保存/);
});
